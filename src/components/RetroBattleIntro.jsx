function PixelSprite({ pixels = [], glow = [], width = 24, height = 24 }) {
  return (
    <svg viewBox={`0 0 ${width} ${height}`} width="100%" height="100%" shapeRendering="crispEdges" aria-hidden="true">
      <rect width={width} height={height} fill="none" />
      {pixels.map(([x, y, color], i) => (
        <rect key={`p-${i}`} x={x} y={y} width="1" height="1" fill={color || 'currentColor'} />
      ))}
      {glow.map(([x, y, color], i) => (
        <rect key={`g-${i}`} x={x} y={y} width="1" height="1" fill={color} />
      ))}
    </svg>
  )
}

