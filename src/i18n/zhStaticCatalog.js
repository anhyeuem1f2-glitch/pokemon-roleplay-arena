const VI_REMAINING = /[ăâđêôơưáàảãạấầẩẫậắằẳẵặéèẻẽẹếềểễệíìỉĩịóòỏõọốồổỗộớờởỡợúùủũụứừửữựýỳỷỹỵ]/iu

export function translateZhStatic(source) {
  const text = String(source ?? '')
  const core = text.trim()
  if (!core) return text
  const exact = ZH_STATIC_CATALOG[core]
  if (exact) return exact
  for (const [pattern, render] of ZH_DYNAMIC_PATTERNS) {
    const match = core.match(pattern)
    if (match) return render(...match)
  }
  // Chỉ fallback cụm từ với label ngắn. Văn dài phải được dịch exact ở catalog
  // để tránh tạo câu Trung khó đọc.
  if (core.length <= 96) {
    let out = core
    for (const [vi, zh] of ZH_OFFLINE_PHRASES) out = out.replaceAll(vi, zh)
    if (out !== core && !VI_REMAINING.test(out)) return out
  }
  return null
}

export function hasZhStaticTranslation(source) {
  const core = String(source ?? '').trim()
  if (!core) return true
  if (ZH_STATIC_CATALOG[core]) return true
  return ZH_DYNAMIC_PATTERNS.some(([pattern]) => pattern.test(core))
}
